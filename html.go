package main

import (
	"cmp"
	"html/template"
	"io"
	"slices"
	"time"
)

// htmlReport is the data passed to reportTemplate.
type htmlReport struct {
	Meta     ScanMeta
	Duration string // empty when the start time is unknown
	Services []serviceCount
	Results  []Result
	Finished time.Time
}

// serviceCount is one row of the report's per-service summary.
type serviceCount struct {
	Name  string
	Count int
}

// writeHTML renders results as a self-contained HTML5 report. All dynamic
// content is escaped by html/template.
func writeHTML(w io.Writer, results []Result, meta ScanMeta) error {
	report := htmlReport{
		Meta:     meta,
		Services: countServices(results),
		Results:  results,
		Finished: meta.FinishedAt,
	}
	if report.Finished.IsZero() {
		report.Finished = time.Now()
	}
	if !meta.StartedAt.IsZero() {
		report.Duration = report.Finished.Sub(meta.StartedAt).Round(time.Millisecond).String()
	}
	return reportTemplate.Execute(w, report)
}

// countServices tallies results by service, most common first.
func countServices(results []Result) []serviceCount {
	counts := make(map[string]int)
	for _, r := range results {
		counts[r.Service]++
	}
	out := make([]serviceCount, 0, len(counts))
	for name, n := range counts {
		out = append(out, serviceCount{name, n})
	}
	slices.SortFunc(out, func(a, b serviceCount) int {
		if c := cmp.Compare(b.Count, a.Count); c != 0 {
			return c
		}
		return cmp.Compare(a.Name, b.Name)
	})
	return out
}

